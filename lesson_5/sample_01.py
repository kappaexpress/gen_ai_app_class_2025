#!/usr/bin/env python3
# 四則計算のサンプル

def main():
    # 足し算
    print(3 + 15)  # addition

    # 引き算
    print(10 - 2)  # subtraction

    # 割り算
    print(90 / 3)  # division

    # 掛け算
    print(51 * 5)  # multiplication

    # べき乗
    print(2 ** 3)  # exponentiation (2の3乗)

    # 余り
    print(10 % 3)  # modulo (10を3で割った余り)

if __name__ == "__main__":
    main()
